namespace WeaponGame;

/// <summary>
/// Определяет контракт для объектов, поддерживающих перезарядку.
/// Класс, реализующий этот интерфейс, должен предоставить собственную
/// реализацию метода Reload().
/// </summary>
public interface IReloadable
{
    /// <summary>
    /// Выполняет перезарядку оружия.
    /// Конкретный способ перезарядки определяется классом,
    /// реализующим интерфейс.
    /// </summary>
    void Reload();
}