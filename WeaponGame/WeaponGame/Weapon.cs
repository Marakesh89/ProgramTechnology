namespace WeaponGame;

/// <summary>
/// Представляет базовый абстрактный класс игрового оружия.
/// Содержит общие характеристики оружия и определяет общий интерфейс
/// для всех производных классов.
/// Напрямую создать экземпляр этого класса нельзя.
/// Для создания конкретного оружия необходимо использовать один
/// из производных классов, например Sword, Bow или Staff.
/// </summary>
public abstract class Weapon
{
    /// <summary>
    /// Уникальный идентификатор оружия.
    /// Используется для различения отдельных экземпляров оружия.
    /// </summary>
    private int _id;

    /// <summary>
    /// Получает или задаёт название оружия.
    /// Например, Excalibur или Longbow.
    /// </summary>
    public string Name { get; set; }

    /// <summary>
    /// Получает или задаёт урон, наносимый оружием за одну атаку.
    /// </summary>
    public int Damage { get; set; }

    /// <summary>
    /// Получает или задаёт скорость атаки.
    /// Значение показывает, сколько атак оружие способно выполнять
    /// за одну единицу времени.
    /// </summary>
    public double AttackSpeed { get; set; }

    /// <summary>
    /// Получает или задаёт тип оружия.
    /// По умолчанию устанавливается значение WeaponType.Melee.
    /// </summary>
    public WeaponType Type { get; set; } = WeaponType.Melee;

    /// <summary>
    /// Вычисляет урон оружия в секунду.
    /// Значение рассчитывается как произведение урона одной атаки
    /// на скорость атаки.
    /// </summary>
    public double DamagePerSecond => Damage * AttackSpeed;

    /// <summary>
    /// Создаёт экземпляр базового оружия и инициализирует его основные характеристики.
    /// </summary>
    /// <param name="id">Идентификатор оружия.</param>
    /// <param name="name">Название оружия.</param>
    /// <param name="damage">Урон одной атаки.</param>
    public Weapon(int id, string name, int damage)
    {
        _id = id;
        Name = name;
        Damage = damage;
        AttackSpeed = 0;
    }

    /// <summary>
    /// Создаёт оружие, используя упрощённый конструктор.
    /// Идентификатор и урон устанавливаются в ноль.
    /// Для инициализации основных параметров вызывается другой конструктор
    /// этого же класса.
    /// </summary>
    /// <param name="name">Название оружия.</param>
    public Weapon(string name) : this(0, name, 0)
    {
    }

    /// <summary>
    /// Выполняет атаку с использованием конкретного типа оружия.
    /// Реализация метода должна быть определена в производном классе.
    /// </summary>
    public abstract void Attack();
}